"""Add owned supplemental consumers to the generated cache, never saved bindings.

Only an unambiguous Live/Film/Series group is eligible. Preserve every source
path, all foreign rows, user order, and the original upstream generated bytes.
The existing consumer snapshot and atomic compare/replace own installation.
"""
import xml.etree.ElementTree as E
from urllib.parse import urlsplit,parse_qs
from widget_six_sources import CORE,EXTRAS
BEGIN=b'<!-- XCMate.SixRows.begin -->'
END=b'<!-- XCMate.SixRows.end -->'

def params(node):return {n['attrs'].get('name'):n['attrs'].get('value','') for n in node['children'] if n['tag']=='param'}
def own_groups(data):
 from widget_skin50 import spans
 from widget_reload78 import directory_uri89
 groups={};nodes=spans(data)
 for node in nodes:
  if node['tag']!='include' or node['attrs'].get('content') not in ('XCMate80.MediaRow','XCMate50.LiveRow'):continue
  values=params(node)
  try:q=parse_qs(urlsplit(directory_uri89(values.get('widgetPath',''))).query)
  except ValueError:continue
  kind=CORE.get(q.get('action',[''])[0])
  if not kind or (kind=='live')!=(node['attrs']['content']=='XCMate50.LiveRow'):continue
  key=(values.get('submenuid'),q.get('pid',[''])[0]);groups.setdefault(key,{})[kind]=(node,values)
 return [(key,group) for key,group in groups.items() if set(group)=={'live','vod','series'}]

def block(series,tail):
 values=series[1];parts=[]
 if not values.get('widgetid','').isdigit() or not tail.isdigit():raise ValueError('SIX_ROWS_FOCUS_UNVERIFIED')
 for kind,title,cid,target in EXTRAS:
  call=E.Element('include',content='XCMate.SixRows.Row',condition=series[0]['attrs'].get('condition','true'))
  custom=dict(values,widgetid=str(cid),widgetName=title,widgetTarget=target,widgetPath='',widgetLimit='6' if kind=='mp3' else '24',widgetSortBy='',widgetSortOrder='',xcmateKind=kind,
   up75='SetFocus($INFO[Window(Home).Property(XCMate.SixRows.'+kind+'.Up)])',down75='SetFocus($INFO[Window(Home).Property(XCMate.SixRows.'+kind+'.Down)])',xcmateTail=tail)
  for name,value in custom.items():E.SubElement(call,'param',name=name,value=value)
  parts.append(E.tostring(call,encoding='utf-8'))
 return BEGIN+b''.join(parts)+END

def patch(data):
 from widget_skin50 import spans,edit
 roots=own_groups(data)
 if len(roots)!=1:return data
 _,group=roots[0];series=group['series'];node,values=series
 directional='SetFocus($INFO[Window(Home).Property(XCMate.SixRows.series.Down)])'
 existing=data.count(BEGIN)
 if existing:
  if existing!=1 or data.count(END)!=1:raise ValueError('SIX_ROWS_UNVERIFIED')
  start=data.index(BEGIN);end=data.index(END)+len(END)
  calls=E.fromstring(b'<includes>'+data[start+len(BEGIN):end-len(END)]+b'</includes>')
  tails={n.get('value','') for n in calls.findall("include/param[@name='xcmateTail']")}
  if len(tails)!=1:raise ValueError('SIX_ROWS_UNVERIFIED')
  tail=tails.pop()
  if data[start:end]!=block(series,tail) or values.get('down75')!=directional:raise ValueError('SIX_ROWS_UNVERIFIED')
  return data
 if b'XCMate.SixRows.Row' in data or END in data:raise ValueError('SIX_ROWS_UNVERIFIED')
 all_ids={n['attrs'].get('value') for n in spans(data) if n['tag']=='param' and n['attrs'].get('name')=='widgetid'}
 if any(str(cid) in all_ids for _,_,cid,_ in EXTRAS):raise ValueError('SIX_ROWS_CONTROL_COLLISION')
 tail=values.get('down75','')
 addition=block(series,tail)
 changes=[]
 down=[n for n in node['children'] if n['tag']=='param' and n['attrs'].get('name')=='down75']
 if len(down)!=1:raise ValueError('SIX_ROWS_FOCUS_UNVERIFIED')
 field=down[0];replacement=E.Element('param',name='down75',value=directional)
 changes.append((field['start'],field['end']+len(b'</param>') if not field.get('selfclosing',False) and data[field['open']-2:field['open']]!=b'/>' else field['open'],E.tostring(replacement,encoding='utf-8')))
 # Insert after the inactive LiveRow alias for the same series, if present.
 after=node['end']+len(b'</include>')
 for item in spans(data):
  if item['tag']=='include' and item['attrs'].get('content')=='XCMate50.LiveRow' and params(item).get('widgetid')==values['widgetid']:after=max(after,item['end']+len(b'</include>'))
 changes.append((after,after,addition))
 return edit(data,changes)

def runtime_binding(data):
 roots=own_groups(data)
 if len(roots)!=1 or data.count(BEGIN)!=1:return None
 key,group=roots[0];tree=E.fromstring(b'<includes>'+data.split(BEGIN,1)[1].split(END,1)[0]+b'</includes>')
 tail=tree.find("include/param[@name='xcmateTail']")
 if tail is None or not tail.get('value','').isdigit():return None
 return {'pid':key[1],'live':int(group['live'][1]['widgetid']),'vod':int(group['vod'][1]['widgetid']),'series':int(group['series'][1]['widgetid']),'tail':int(tail.get('value'))}
